RULES: dict[str, Rule] = {rule.rule_id: rule for rule in _RULES}
if len(RULES) != len(_RULES):  # pragma: no cover - garde-fou de développement
    raise RuntimeError("Identifiants de règles dupliqués dans le registre.")


def get_rule(rule_id: str) -> Rule:
    """Retourne la règle ``rule_id`` (erreur explicite si elle n'existe pas)."""
    try:
        return RULES[rule_id]
    except KeyError as exc:
        raise KeyError(f"Règle d'audit inconnue : {rule_id!r}") from exc


def rules_frame() -> pd.DataFrame:
    """Catalogue des règles sous forme de DataFrame (documentation, notebooks)."""
    return pd.DataFrame(
        [
            {
                "rule_id": r.rule_id,
                "detecteur": r.detector,
                "categorie": r.category.value,
                "gravite": r.severity.value,
                "diagnostic": r.status.value,
                "titre": r.title,
                "variables": r.columns,
                "justification": r.justification,
                "impact_ml": r.potential_impact,
                "action_envisagee": r.suggested_action,
                "methode": r.detection_method,
            }
            for r in _RULES
        ]
    )
